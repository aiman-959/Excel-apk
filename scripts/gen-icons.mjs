/**
 * Generates every Petak icon/splash asset from assets/brand/petak-logo.svg.
 *   node scripts/gen-icons.mjs
 * Needs Playwright's Chromium for PNG rasterising (set CHROMIUM_PATH to use another Chromium).
 *
 * Adaptive icon geometry: the 3x3 plot grid spans x/y 44..196 in the 240-unit master.
 * The furthest visible point (outer rounded corner) is 104.2 units from the centre, which
 * must stay inside Android's 66 dp safe-zone circle (r = 33 dp) on the 108 dp canvas.
 * We use r = 32 dp -> 0.307 dp/unit -> a 352-unit viewport centred on the logo.
 */
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const res = path.join(root, 'android/app/src/main/res');
const master = fs.readFileSync(path.join(root, 'assets/brand/petak-logo.svg'), 'utf8');

const DARK = '#14532D';
const PLOTS = [
  [44, 44, '#16A34A'], [98, 44, '#22C55E'], [152, 44, '#15803D'],
  [44, 98, '#22C55E'], [98, 98, '#15803D'], [152, 98, '#FBBF24'],
  [44, 152, '#15803D'], [98, 152, '#16A34A'], [152, 152, '#22C55E'],
];
const VIEWPORT = 352;
const OFFSET = (VIEWPORT - 240) / 2; // 56

const rr = (x, y, s = 44, r = 8) =>
  `M${x + r},${y} h${s - 2 * r} a${r},${r} 0 0 1 ${r},${r} v${s - 2 * r} a${r},${r} 0 0 1 -${r},${r} h-${s - 2 * r} a${r},${r} 0 0 1 -${r},-${r} v-${s - 2 * r} a${r},${r} 0 0 1 ${r},-${r} z`;

/** Horizontal stripes of the master's pattern (line at y = 4 mod 8, 2 units thick) inside one plot. */
function stripes(x, y) {
  let d = '';
  for (let yc = Math.floor((y - 4) / 8) * 8 + 4; yc - 1 < y + 44; yc += 8) {
    const top = Math.max(y, yc - 1);
    const bottom = Math.min(y + 44, yc + 1);
    if (bottom > top) d += `M${x},${top} h44 V${bottom} h-44 z `;
  }
  return d.trim();
}

function vector(body) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-icons.mjs from assets/brand/petak-logo.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="${VIEWPORT}" android:viewportHeight="${VIEWPORT}">
    <group android:translateX="${OFFSET}" android:translateY="${OFFSET}">
${body}
    </group>
</vector>
`;
}

const foreground = vector(
  PLOTS.map(
    ([x, y, c]) => `        <group>
            <clip-path android:pathData="${rr(x, y)}" />
            <path android:fillColor="${c}" android:pathData="${rr(x, y)}" />
            <path android:fillColor="#FFFFFF" android:fillAlpha="0.28" android:pathData="${stripes(x, y)}" />
        </group>`,
  ).join('\n'),
);
// Themed icon (Android 13+): single colour, the gold plot stays fully opaque so it still reads as the accent.
const monochrome = vector(
  PLOTS.map(([x, y, c]) => `        <path android:fillColor="#FFFFFF" android:fillAlpha="${c === '#FBBF24' ? '1' : '0.55'}" android:pathData="${rr(x, y)}" />`).join('\n'),
);

const write = (rel, text) => {
  const f = path.join(root, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, text);
  return f;
};

write('android/app/src/main/res/drawable/ic_launcher_foreground.xml', foreground);
write('android/app/src/main/res/drawable/ic_launcher_monochrome.xml', monochrome);
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  write(
    `android/app/src/main/res/mipmap-anydpi-v26/${name}.xml`,
    `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
`,
  );
}
write(
  'android/app/src/main/res/values/ic_launcher_background.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${DARK}</color>
    <color name="splash_background">${DARK}</color>
</resources>
`,
);
// Pre-Android-12 launch window: logo centred on the brand colour (Android 12+ uses the SplashScreen API attributes).
write(
  'android/app/src/main/res/drawable/splash.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background"/>
    <item android:drawable="@drawable/ic_launcher_foreground" android:gravity="center" android:width="216dp" android:height="216dp"/>
</layer-list>
`,
);

// ---------------------------------------------------------------- PNGs
const noRadius = master.replace('<rect width="240" height="240" rx="56" fill="#14532D"/>', '<rect width="240" height="240" fill="#14532D"/>');
const round = master.replace(
  '<rect width="240" height="240" rx="56" fill="#14532D"/>',
  '<circle cx="120" cy="120" r="120" fill="#14532D"/>',
);
const sized = (svg, n) => svg.replace('width="240" height="240"', `width="${n}" height="${n}"`);

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const page = await browser.newPage({ deviceScaleFactor: 1 });
async function png(svg, n, rel) {
  await page.setViewportSize({ width: n, height: n });
  await page.setContent(`<html><body style="margin:0;background:transparent">${sized(svg, n)}</body></html>`);
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  await page.screenshot({ path: file, omitBackground: true, clip: { x: 0, y: 0, width: n, height: n } });
  return file;
}
const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, n] of Object.entries(densities)) {
  await png(master, n, `android/app/src/main/res/mipmap-${d}/ic_launcher.png`);
  await png(round, n, `android/app/src/main/res/mipmap-${d}/ic_launcher_round.png`);
}
await png(noRadius, 512, 'assets/brand/petak-playstore-512.png'); // Play applies its own corner mask
await png(master, 1024, 'assets/brand/petak-logo-1024.png');
await png(master, 180, 'public/apple-touch-icon.png');
await png(master, 192, 'public/icon-192.png');
await png(master, 512, 'public/icon-512.png');
await png(master, 32, 'public/favicon-32.png');
fs.copyFileSync(path.join(root, 'assets/brand/petak-logo.svg'), path.join(root, 'public/favicon.svg'));
await browser.close();
console.log('Icons generated.');
