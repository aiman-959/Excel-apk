/**
 * Regenerates THIRD_PARTY_LICENSES.md from the installed production dependency tree.
 *   node scripts/gen-licenses.mjs
 * Fails if any production dependency has a licence that is not on the GPLv3-compatible allow list.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const COMPATIBLE = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'Unlicense', 'Zlib', 'BlueOak-1.0.0', 'CC0-1.0', 'Python-2.0', 'GPL-3.0-only', 'GPL-3.0-or-later', 'LGPL-3.0-or-later', 'MIT*', 'MIT/X11']);
// Packages whose package.json lacks a licence field (verified manually from their LICENSE/README)
const MANUAL = { buffers: 'MIT/X11' };

const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 }));
const seen = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    const key = `${name}@${info.version}`;
    if (!info.version || seen.has(key)) continue;
    let pj = {};
    const dir = info.path ?? path.join(root, 'node_modules', name);
    try {
      pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    } catch {
      /* ignore */
    }
    let lic = typeof pj.license === 'string' ? pj.license : pj.license?.type ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type ?? l).join(' OR ') : undefined);
    lic = lic ?? MANUAL[name] ?? 'UNKNOWN';
    const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url ?? pj.homepage ?? '';
    seen.set(key, { name, version: info.version, license: lic, repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') });
    walk(info.dependencies);
  }
})(tree.dependencies);

const ok = (l) => l.split(/\s+(?:OR|AND)\s+|[()]/).filter(Boolean).some((x) => COMPATIBLE.has(x.trim()));
const bad = [...seen.values()].filter((p) => !ok(p.license));
const direct = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).dependencies);

const KEY = [
  ['Univer (@univerjs/*)', 'Apache-2.0', 'Spreadsheet grid, editing, formatting, filter/sort/find, conditional formatting', 'https://github.com/dream-num/univer'],
  ['HyperFormula', 'GPL-3.0-only', 'Formula engine (used under its GPLv3 licence: licenseKey "gpl-v3")', 'https://github.com/handsontable/hyperformula'],
  ['SheetJS Community Edition (xlsx)', 'Apache-2.0', 'CSV / XLS / ODS import and CSV export', 'https://git.sheetjs.com/sheetjs/sheetjs'],
  ['ssf (SheetJS number formats)', 'Apache-2.0', 'Excel-compatible TEXT() formatting', 'https://github.com/SheetJS/ssf'],
  ['ExcelJS', 'MIT', 'xlsx/xlsm read and write with styles', 'https://github.com/exceljs/exceljs'],
  ['fflate', 'MIT', 'Zip handling for VBA preservation', 'https://github.com/101arrowz/fflate'],
  ['Arquero', 'BSD-3-Clause', 'Data transforms and pivot tables', 'https://github.com/uwdata/arquero'],
  ['Apache ECharts', 'Apache-2.0', 'Bar / line / pie charts', 'https://github.com/apache/echarts'],
  ['React', 'MIT', 'User interface', 'https://github.com/facebook/react'],
  ['Capacitor', 'MIT', 'Android wrapper', 'https://github.com/ionic-team/capacitor'],
  ['Lucide', 'ISC', 'Icons', 'https://github.com/lucide-icons/lucide'],
  ['RxJS', 'Apache-2.0', 'Required by Univer', 'https://github.com/ReactiveX/rxjs'],
];

const md = `# Third-party licences

Petak is licensed under the **GNU General Public License v3.0** (GPL-3.0-only, see \`LICENSE\`).
All bundled third-party components use licences that are compatible with GPLv3:

* **MIT, ISC, BSD-2/3-Clause, 0BSD, Zlib, BlueOak-1.0.0, Unlicense** — permissive, GPLv3-compatible.
* **Apache-2.0** — compatible with GPL**v3** (not with GPLv2), which is why Petak is GPLv3.
* **GPL-3.0-only** (HyperFormula) — same licence family; it is the reason the project is GPL-3.0-only rather than "or later".
* **JSZip** is dual-licensed "MIT OR GPL-3.0-or-later"; it is used under MIT.

## Main components

| Component | Licence | Used for | Source |
|---|---|---|---|
${KEY.map((k) => `| ${k[0]} | ${k[1]} | ${k[2]} | ${k[3]} |`).join('\n')}

Android build-time tools (Gradle, Android Gradle Plugin, AndroidX libraries pulled in by Capacitor) are Apache-2.0.

## Fonts and artwork

| Asset | Licence | Notes |
|---|---|---|
| Space Grotesk Bold (Latin subset, \`src/assets/fonts/space-grotesk-latin-700-normal.woff2\`) | SIL Open Font License 1.1 | Used for the "Petak" wordmark. Licence text: \`src/assets/fonts/SpaceGrotesk-OFL.txt\`. The OFL allows bundling the font with software under any licence. |
| Petak logo and icons (\`assets/brand/\`, Android launcher icons) | GPL-3.0-only (part of this project) | Original artwork. |


## Full list of production npm packages (${seen.size})

Generated by \`node scripts/gen-licenses.mjs\`. Direct dependencies are **bold**.
Some packages listed (for example the Node-only parts of ExcelJS's zip reader) are never included in the app bundle.

| Package | Version | Licence | Repository |
|---|---|---|---|
${[...seen.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map((p) => `| ${direct.includes(p.name) ? `**${p.name}**` : p.name} | ${p.version} | ${p.license} | ${p.repo} |`)
  .join('\n')}

Full licence texts are in each package's directory under \`node_modules/\` and in the upstream repositories above.
`;
fs.writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.md'), md);
console.log(`Wrote THIRD_PARTY_LICENSES.md (${seen.size} packages)`);
if (bad.length) {
  console.error('Licences needing review:', bad.map((b) => `${b.name}@${b.version} (${b.license})`).join(', '));
  process.exit(1);
}
