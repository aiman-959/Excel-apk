/**
 * Size report: web bundle (by chunk, raw / gzip), on-demand remote modules and the
 * APKs that exist in android/app/build/outputs. Writes SIZE.md and prints it.
 *   node scripts/size-report.mjs [--summary]   (--summary also appends to $GITHUB_STEP_SUMMARY)
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dist = path.join(root, 'dist');
const mb = (b) => (b / 1e6).toFixed(2) + ' MB';
const kb = (b) => (b < 1e6 ? (b / 1e3).toFixed(0) + ' kB' : mb(b));

if (!fs.existsSync(dist)) {
  console.error('Run `npm run build` first.');
  process.exit(1);
}

// which chunks the start page loads (index.html + their static imports)
const html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const startFiles = new Set([...html.matchAll(/(?:src|href)="\.\/(assets\/[^"]+)"/g)].map((m) => m[1]));

const files = [];
const walk = (dir) => {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
};
walk(dist);

const rows = files.map((p) => {
  const rel = path.relative(dist, p).replace(/\\/g, '/');
  const buf = fs.readFileSync(p);
  const gz = /\.(js|css|html|svg|json)$/.test(rel) ? zlib.gzipSync(buf, { level: 9 }).length : buf.length;
  const kind = /\.worker-/.test(rel) ? 'worker (started on use)' : startFiles.has(rel) ? 'start' : /\.(js|css)$/.test(rel) ? 'lazy (loaded on use)' : 'static';
  return { rel, raw: buf.length, gz, kind };
});
rows.sort((a, b) => b.raw - a.raw);

const sum = (k, f = () => true) => rows.filter(f).reduce((t, r) => t + r[k], 0);
const group = (kind) => rows.filter((r) => r.kind === kind);

// remote modules (kept out of the APK)
const remoteSrc = fs.readFileSync(path.join(root, 'src/modules/remote.ts'), 'utf8');
const dl = /approxDownloadBytes: variant === 'eh' \? ([\d.e]+)/.exec(remoteSrc)?.[1];
const inst = /approxInstalledBytes: variant === 'eh' \? ([\d.e]+)/.exec(remoteSrc)?.[1];
const ver = /DUCKDB_VERSION = '([^']+)'/.exec(remoteSrc)?.[1];

// APKs
const apkDirs = ['android/app/build/outputs/apk/release', 'android/app/build/outputs/apk/debug'].map((d) => path.join(root, d));
const apks = apkDirs.flatMap((d) => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => f.endsWith('.apk')).map((f) => ({ f: path.relative(root, path.join(d, f)), size: fs.statSync(path.join(d, f)).size })) : []));

const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
let md = `# Petak ${version} — size report\n\nGenerated by \`node scripts/size-report.mjs\`. Budget: base APK under 40 MB.\n\n`;
md += `## APKs\n\n`;
if (apks.length) {
  md += `| APK | Size |\n|---|---:|\n` + apks.map((a) => `| \`${a.f}\` | ${mb(a.size)} |`).join('\n') + '\n\n';
  md += `The ABI APKs are the same size as the universal one: Petak has no native code (the grid, formula engine and file IO are JavaScript, DuckDB is WebAssembly), so per-ABI splits cannot remove anything. They are produced so stores and side-loaders can choose by ABI.\n\n`;
} else md += `_No APKs built yet (run \`npm run android:release\`)._\n\n`;

md += `## Web bundle inside the APK\n\n| Part | Files | Raw | gzip |\n|---|---:|---:|---:|\n`;
for (const k of ['start', 'lazy (loaded on use)', 'worker (started on use)', 'static']) {
  const g = group(k);
  md += `| ${k} | ${g.length} | ${mb(sum('raw', (r) => r.kind === k))} | ${mb(sum('gz', (r) => r.kind === k))} |\n`;
}
md += `| **total** | ${rows.length} | **${mb(sum('raw'))}** | **${mb(sum('gz'))}** |\n\n`;
md += `Assets are stored deflate-compressed in the APK (roughly the gzip column).\n\n`;

md += `### Largest files\n\n| File | Loaded | Raw | gzip |\n|---|---|---:|---:|\n`;
md += rows.filter((r) => r.raw > 20000).map((r) => `| \`${r.rel}\` | ${r.kind} | ${kb(r.raw)} | ${kb(r.gz)} |`).join('\n') + '\n\n';

md += `## Modules downloaded on first use (not in the APK)\n\n| Module | Download | On device | When |\n|---|---:|---:|---|\n`;
md += `| DuckDB ${ver} (WebAssembly) | ${mb(+dl)} | ${mb(+inst)} | first use of Data → Data model; size shown and confirmed first, removable in About |\n\n`;

md += `## What was removed\n\n`;
md += `- Univer hyphenation dictionaries for 77 languages (≈4.6 MB): replaced at build time by empty patterns (\`vite.config.ts\`); spreadsheet cells do not hyphenate and English is built in.\n`;
md += `- Android translations bundled by AndroidX (\`localeFilters = ["en"]\`).\n`;
md += `- Unused Java/Kotlin code and resources (R8 \`minifyEnabled\` + \`shrinkResources\`).\n`;
md += `- One font file only: Space Grotesk Bold, Latin subset (${kb(rows.find((r) => /space-grotesk/.test(r.rel))?.raw ?? 0)}), for the wordmark; the UI uses the system font.\n`;
md += `- Source maps are not shipped; JavaScript is minified and tree-shaken, features are split into lazy chunks and workers.\n`;

fs.writeFileSync(path.join(root, 'SIZE.md'), md);
console.log(md);
if (process.argv.includes('--summary') && process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, md);
