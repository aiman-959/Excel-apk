import { chromium, devices } from 'playwright';
import ExcelJS from 'exceljs';
import path from 'node:path';
import fs from 'node:fs';
const OUT = path.resolve('tests/audit/out');
const wb = new ExcelJS.Workbook(); const ws = wb.addWorksheet('Data');
ws.addRow(['Item', 'Qty', 'Price']); ws.addRow(['A', 2, 10]); ws.addRow(['B', 3, 20]);
wb.definedNames.add('Data!$B$2:$B$3', 'Qty');
ws.getCell('E1').value = { formula: 'SUM(Qty)', result: 5 };
ws.addTable({ name: 'Sales', ref: 'G1', headerRow: true, columns: [{ name: 'Item' }, { name: 'Amount' }], rows: [['x', 5], ['y', 7]] });
ws.getCell('E2').value = { formula: 'SUM(Sales[Amount])', result: 12 };
ws.getCell('E3').value = { formula: 'SUM(B2:B3*C2:C3)', result: 80 };
ws.getColumn(3).numFmt = '#,##0.00';
ws.getCell('E4').value = { formula: 'TODAY()-DATE(2026,1,1)' };
ws.pageSetup = { orientation: 'landscape', fitToPage: true, printTitlesRow: '1:1' };
ws.getCell('A6').value = { richText: [{ text: 'bold ', font: { bold: true } }, { text: 'red', font: { color: { argb: 'FFFF0000' } } }] };
const f = path.join(OUT, 'names.xlsx'); await wb.xlsx.writeFile(f);
const b = await chromium.launch(); const ctx = await b.newContext({ ...devices['Pixel 7'] }); const page = await ctx.newPage();
await page.goto('http://localhost:4173/?fresh'); await page.waitForFunction(() => window.__doc?.snapshot?.sheets?.length > 0);
const [ch] = await Promise.all([page.waitForEvent('filechooser'), page.click('[data-testid=open]')]); await ch.setFiles(f);
await page.waitForFunction(() => window.__doc.snapshot.file.name === 'names.xlsx'); await page.evaluate(() => window.__doc.bridge.idle()); await page.waitForTimeout(500);
const v = (r) => page.evaluate((r) => JSON.stringify(window.__doc.wb.getActiveSheet().getRange(r).getCellData()), r);
console.log('SUM(Qty) named range:', await v('E1'));
console.log('SUM(Sales[Amount]) structured ref:', await v('E2'));
console.log('array formula:', await v('E3'));
console.log('rich text A6:', await v('A6'));
const { unzipSync, strFromU8 } = await import('fflate');
const out = unzipSync(new Uint8Array(await page.evaluate(async () => Array.from(new Uint8Array((await window.__doc.serialize('xlsx')).data)))));
const s1 = strFromU8(out['xl/worksheets/sheet1.xml']);
console.log('after save: table part kept', Object.keys(out).some((k) => k.includes('tables/')), '| pageSetup landscape kept', /orientation="landscape"/.test(s1), '| print titles kept', /_xlnm.Print_Titles/.test(strFromU8(out['xl/workbook.xml'])), '| column numFmt kept', /<col [^>]*style=/.test(s1), '| rich text runs kept', /<r>/.test(strFromU8(out['xl/sharedStrings.xml'] ?? '')));
await b.close();
